inline QString tr(const QString &key) {
    if (STRINGS.contains(currentLanguage) && STRINGS[currentLanguage].contains(key)) {
        return STRINGS[currentLanguage][key];
    }
    if (STRINGS.contains("en") && STRINGS["en"].contains(key)) {
        return STRINGS["en"][key];
    }
    return key;
}

