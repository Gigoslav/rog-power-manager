inline QString currentLanguage = "de";

inline void detectLanguage() {
    QProcessEnvironment env = QProcessEnvironment::systemEnvironment();
    QStringList vars = {"LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"};
    for (const auto &v : vars) {
        QString val = env.value(v);
        if (!val.isEmpty()) {
            currentLanguage = val.toLower().startsWith("de") ? "de" : "en";
            return;
        }
    }
    QString sysLoc = QLocale::system().name();
    currentLanguage = sysLoc.toLower().startsWith("de") ? "de" : "en";
}

